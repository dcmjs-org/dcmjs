// Catalog builder — pure (no I/O, no import.meta), so the CI gates can
// import it under jest. The CLI shell that writes files is generate-schema.mjs.
// The attribute rules come from the shipped src module, which derives them
// from the packed dictionary — this file only projects them into the two
// static artifacts (the .d.ts and the JSON Schema).
import { createHash } from "crypto";
import { naturalizedRules } from "../src/schema/naturalizedRules.js";
import { parseVm, VR_SCALAR } from "./schemaRules.mjs";

export function buildCatalog() {
    const attributes = naturalizedRules.attributes;
    const dictionaryHash = createHash("sha256")
        .update(JSON.stringify(attributes))
        .digest("hex")
        .slice(0, 16);
    return {
        version: naturalizedRules.version,
        dictionaryHash,
        vrFormats: naturalizedRules.vrFormats,
        attributes,
        envelope: naturalizedRules.envelope
    };
}

function scalarFor(vr) {
    const scalar = VR_SCALAR[vr];
    if (!scalar) {
        throw new Error(`no TS projection for VR "${vr}"`);
    }
    return scalar;
}

export function tsTypeFor(entry) {
    const vrs = Array.isArray(entry.vr) ? entry.vr : [entry.vr];
    // Per-VR: sequences and binary VRs ignore the VM (a binary Value lists
    // frames, or is one bulk reference); everything else follows the VM
    // rule. Every value can be null: a present-but-empty element
    // naturalizes as null, and a list can hold null entries.
    const parts = new Set(
        vrs.map(vr => {
            const scalar = scalarFor(vr);
            if (scalar === "NaturalizedDataset[]") {
                // A single-item sequence naturalizes as the item itself
                // (with a hidden [0], length, and an iterator), not an array.
                return "NaturalizedDataset | NaturalizedDataset[]";
            }
            if (scalar === "BinaryValue") {
                return "BinaryValue | BinaryValue[]";
            }
            if (!entry.multi) {
                return scalar;
            }
            return `(${scalar} | null)[]`;
        })
    );
    return `${[...parts].join(" | ")} | null`;
}

function tsPropName(keyword) {
    return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(keyword)
        ? keyword
        : JSON.stringify(keyword);
}

export function typesSource(catalog) {
    const lines = [
        "// GENERATED by generate/generate-schema.mjs — DO NOT EDIT.",
        `// Schema version ${catalog.version} (dictionary ${catalog.dictionaryHash}).`,
        "// Naturalized data shape ONLY — this is not a full dcmjs API typing.",
        "",
        "export interface PersonName {",
        "    Alphabetic?: string;",
        "    Ideographic?: string;",
        "    Phonetic?: string;",
        "}",
        "export type BulkDataReference = { BulkDataURI: string };",
        "export type InlineBinaryReference = { InlineBinary: string };",
        "export type BinaryValue = ArrayBuffer | BulkDataReference | InlineBinaryReference;",
        "",
        "export interface NaturalizedDataset {"
    ];
    // buildAttributeRules guarantees unique keywords, so each entry is one property.
    for (const [tag, entry] of Object.entries(catalog.attributes)) {
        const type = tsTypeFor(entry);
        const vrLabel = Array.isArray(entry.vr)
            ? entry.vr.join("/")
            : entry.vr;
        lines.push(`    /** ${tag} · VR ${vrLabel} · VM ${entry.vm} */`);
        lines.push(`    ${tsPropName(entry.keyword)}?: ${type};`);
    }
    lines.push(
        "    /** Private ('<slot>:<creator>') and unknown-tag keys */"
    );
    lines.push("    [privateOrUnknown: string]: unknown;");
    lines.push("}");
    lines.push("");
    // Declarations for the module exports of src/schema/naturalizedRules.js,
    // so `import { naturalizedRules } from "@dcmjs-org/schemas"` type-checks.
    lines.push(
        `export interface AttributeRule {
    keyword: string;
    vr: string | string[];
    vm: string;
    multi: boolean;
}
export interface VrFormat {
    maxLength?: number;
    pattern?: string;
}
export interface NaturalizedEnvelope {
    cardinality: string;
    values: string;
    personName: string;
    sequences: string;
    privateTags: string;
    unknownTags: string;
    rawRetention: string;
    bulk: string;
}
export declare const SCHEMA_VERSION: string;
export declare const KNOWN_VRS: Set<string>;
export declare const BINARY_VRS: Set<string>;
export declare const MULTI_VR: Record<string, string[]>;
export declare const vrFormats: Record<string, VrFormat>;
export declare const EXCLUDED_TAGS: Set<string>;
export declare const KEYWORDLESS_TAGS: Set<string>;
export declare const envelope: NaturalizedEnvelope;
export declare function buildAttributeRules(): Record<string, AttributeRule>;
export declare function getAttributeRule(
    tag: string
): AttributeRule | undefined;
export declare const naturalizedRules: {
    version: string;
    envelope: NaturalizedEnvelope;
    vrFormats: Record<string, VrFormat>;
    readonly attributes: Record<string, AttributeRule>;
};
`
    );
    return lines.join("\n");
}

export function jsonSchemaFor(entry, catalog) {
    const vrs = Array.isArray(entry.vr) ? entry.vr : [entry.vr];
    const scalarTs = [...new Set(vrs.map(scalarFor))];
    const isSq = scalarTs.length === 1 && scalarTs[0] === "NaturalizedDataset[]";
    const isBinary = scalarTs.length === 1 && scalarTs[0] === "BinaryValue";
    const isPn = scalarTs.length === 1 && scalarTs[0] === "PersonName";
    // Value space follows envelope.values: "asReturned" — every value can
    // be null (a present-but-empty element naturalizes as null, and a list
    // can hold null entries). The Part 5 formats are the x-dicom-format
    // annotation, not validation keywords.
    let item;
    if (isPn) {
        item = { $ref: "#/$defs/personName" };
    } else if (scalarTs.length === 1 && scalarTs[0] === "string") {
        item = { type: ["string", "null"] };
    } else if (scalarTs.length === 1 && scalarTs[0] === "number") {
        item = { type: ["number", "null"] };
    } else {
        item = {}; // bigint, VR unions: annotation-only
    }
    let prop;
    if (isSq) {
        // Shared $defs entries: inlining a multi-branch shape into every
        // property overflows ajv's codegen on this schema.
        prop = { $ref: "#/$defs/sequenceValue" };
    } else if (isBinary) {
        prop = { $ref: "#/$defs/binaryValue" };
    } else if (entry.multi) {
        prop = { type: ["array", "null"], items: item };
        const vm = parseVm(entry.vm);
        if (vm.min > 1) {
            prop.minItems = vm.min;
        }
        if (vm.max !== null) {
            prop.maxItems = vm.max;
        }
    } else {
        prop = { ...item };
    }
    const fmt = vrs.length === 1 ? catalog.vrFormats[vrs[0]] : undefined;
    if (fmt) {
        prop["x-dicom-format"] = fmt;
    }
    prop["x-dicom-vr"] = Array.isArray(entry.vr)
        ? entry.vr.join("/")
        : entry.vr;
    prop["x-dicom-vm"] = entry.vm;
    return prop;
}

export function jsonSchemaSource(catalog) {
    const properties = {};
    for (const [tag, entry] of Object.entries(catalog.attributes)) {
        properties[entry.keyword] = {
            ...jsonSchemaFor(entry, catalog),
            "x-dicom-tag": tag
        };
    }
    const doc = {
        $schema: "https://json-schema.org/draft/2020-12/schema",
        $id: "https://dcmjs.org/schema/naturalized.schema.json",
        title: "dcmjs naturalized dataset",
        "x-dicom-schema-version": catalog.version,
        "x-dicom-dictionary-hash": catalog.dictionaryHash,
        type: "object",
        properties,
        additionalProperties: true,
        $defs: {
            // A single-item sequence naturalizes as the item itself, not
            // an array, so a sequence value is a dataset or a dataset array
            // (or null when the element is present but empty).
            sequenceValue: {
                anyOf: [
                    { type: "null" },
                    { type: "array", items: { $ref: "#" } },
                    { $ref: "#" }
                ]
            },
            // A binary value is a frame list, or one bulk reference object
            // ({BulkDataURI} | {InlineBinary}) when the bytes are not inline.
            binaryValue: {
                anyOf: [
                    { type: "null" },
                    { type: "array", items: {} },
                    { type: "object" }
                ]
            },
            // The PN component object. Additional properties stay open: a
            // caller-assigned plain string keeps its boxed-String shape
            // until denaturalization.
            personName: {
                anyOf: [
                    { type: "null" },
                    {
                        type: "object",
                        properties: {
                            Alphabetic: { type: ["string", "null"] },
                            Ideographic: { type: ["string", "null"] },
                            Phonetic: { type: ["string", "null"] }
                        }
                    }
                ]
            }
        }
    };
    return JSON.stringify(doc, null, 2) + "\n";
}
