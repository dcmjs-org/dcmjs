// Writes registry/dcmjs/1/naturalized-values/scripts/keywords.ts from the
// dcmjs dictionary. Run it after a dictionary update:
//   node packages/codemods/scripts/generate-keywords.mjs
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import dictionary from "../../../generate/dictionary.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(
    here,
    "../registry/dcmjs/1/naturalized-values/scripts/keywords.ts"
);
const BINARY = new Set(["OB", "OD", "OF", "OL", "OV", "OW", "UN", "SQ"]);

const listVm = new Set();
const personName = new Set();
for (const entry of Object.values(dictionary)) {
    const { name, vr, vm } = entry;
    if (!name || !/^[A-Za-z]/.test(name)) continue;
    // a range VM other than 0-1 can hold one value, and stays a list in 1.0
    if (vm.includes("-") && vm !== "0-1" && !BINARY.has(vr)) listVm.add(name);
    if (vr === "PN" && vm === "1") personName.add(name);
}

const list = set =>
    [...set]
        .sort()
        .map(name => `  '${name}',`)
        .join("\n");
writeFileSync(
    target,
    `// Generated by packages/codemods/scripts/generate-keywords.mjs. Do not edit.

/** The keywords whose VM can hold one value and stays a list in 1.0. */
export const LIST_VM = new Set([
${list(listVm)}
]);

/** The PN keywords with a VM of 1. */
export const PERSON_NAME = new Set([
${list(personName)}
]);
`
);
console.log(`${listVm.size} list keywords, ${personName.size} PN keywords`);
